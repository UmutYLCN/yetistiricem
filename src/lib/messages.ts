function normalizedSource(source: string): { key: string; prefix: string; suffix: string } {
  const key = source.replace(/\s+/g, ' ').trim();
  const prefix = /^\s/.test(source) ? ' ' : '';
  const suffix = /\s$/.test(source) ? ' ' : '';
  return { key, prefix, suffix };
}

/** Translate a complete authored UI phrase; unknown text remains unchanged. */
export function msg(source: string): string {
  const { key, prefix, suffix } = normalizedSource(source);
  const translated = catalogs[currentLanguage()][key];
  return translated ? `${prefix}${translated}${suffix}` : source;
}

export function translateTemplate(source: string, values: Record<string, string | number>): string {
  return msg(source).replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) => String(values[name] ?? match));
}
